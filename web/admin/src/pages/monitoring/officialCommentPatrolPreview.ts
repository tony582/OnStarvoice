    ok: true,
    post: {
      id: post.id,
      title: post.title,
      url: post.url,
      platform: post.platform,
      publishedAt: post.publishedAt,
      officialAccount: post.officialAccount,
    },
    bucket,
    counts: {
      all: post.sentiment.total,
      negative: post.sentiment.negative,
      positive: post.sentiment.positive,
      negativePending: post.todos.negative,
      positivePending: post.todos.positive,
    },
    comparison: {
      latestPatrolledAt: post.lastPatrolledAt,
      previousPatrolledAt: post.previousPatrolledAt,
      baselineOnly: false,
    },
    comments: filtered,
    pagination: {
      page: 1,
      pageSize: 20,
      total: filtered.length,
      totalPages: 1,
    },
